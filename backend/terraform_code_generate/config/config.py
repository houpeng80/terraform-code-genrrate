import os
import yaml

from pathlib import Path
from pydantic import BaseModel, Field
from typing import Self

def _default_config_candidates() -> tuple[Path, ...]:
    backend_dir = Path(__file__).resolve().parents[3]
    repo_root = backend_dir.parent
    return backend_dir / "config.yaml", repo_root / "config.yaml"

class AgentConfig(BaseModel):
    """Config for the Code generate agent"""

    log_level: str = Field(default="info", description="Logging level for code generate agent (debug/info/warning/error)")
    temperature: int = Field(default=0, description="The temperature of the model")
    max_tokens: int = Field(default=1024, description="The max tokens of the model")
    timeout: int = Field(default=300, description="The timeout of the model")
    max_retries: int = Field(default=3, description="The max retries of the model")
    summarization_trigger_messages: int = Field(default=4, description="The messages count when summarization is triggered")
    summarization_trigger_tokens: int = Field(default=1000, description="The tokens count when summarization is triggered")
    model_type: str = Field(default="deepseek", description="Model type for code generate agent (openai/xiaomi/deepseek/qwen/glm)")

    generate_code: bool = Field(default=True, description="Whether generate code (true/false)")
    code_check: bool = Field(default=True, description="Whether check the code when code is generated by sub agent (true/false)")
    code_fix: bool = Field(default=True, description="Whether fix the code when the code should be fixed (true/false)")
    code_retries: int = Field(default=3, description="The retry times when generate code")

    generate_test: bool = Field(default=True, description="Whether generate test (true/false)")
    test_check: bool = Field(default=True, description="Whether check the test when test is generated by sub agent (true/false)")
    test_fix: bool = Field(default=True, description="Whether fix the test when the test should be fixed (true/false)")
    test_retries: int = Field(default=3, description="The retry times when generate test")

    generate_doc: bool = Field(default=True, description="Whether generate doc (true/false)")
    doc_check: bool = Field(default=True, description="Whether check the doc when doc is generated by sub agent (true/false)")
    doc_fix: bool = Field(default=True, description="Whether fix the doc when the doc should be fixed (true/false)")
    doc_retries: int = Field(default=3, description="The retry times when generate doc")

    execute_type: str = Field(default="dynamic_step", description="Plan and execute type for code generate agent (graph/fixed_step/dynamic_step)")
    print_thinking_process: bool = Field(default=True, description="Whether print the thinking process)")

    @classmethod
    def resolve_config_path(cls, config_path: str | None = None) -> Path:
        """Resolve the config file path.

        Priority:
        1. If provided `config_path` argument, use it.
        2. If provided `CODE_GENERATE_AGENT_CONFIG_PATH` environment variable, use it.
        3. Otherwise, search deterministic backend/repository-root defaults from `_default_config_candidates()`.
        """
        if config_path:
            path = Path(config_path)
            if not Path.exists(path):
                raise FileNotFoundError(f"Config file specified by param `config_path` not found at {path}")
            return path
        elif os.getenv("CODE_GENERATE_AGENT_CONFIG_PATH"):
            path = Path(os.getenv("CODE_GENERATE_AGENT_CONFIG_PATH"))
            if not Path.exists(path):
                raise FileNotFoundError(
                    f"Config file specified by environment variable `CODE_GENERATE_AGENT_CONFIG_PATH` not found at {path}")
            return path
        else:
            for path in _default_config_candidates():
                if path.exists():
                    return path
            raise FileNotFoundError("`config.yaml` file not found at the default backend or repository root locations")

    @classmethod
    def from_file(cls, config_path: str | None = None) -> Self:
        """Load config from YAML file.

        See `resolve_config_path` for more details.

        Args:
            config_path: Path to the config file.

        Returns:
            AgentConfig: The loaded config.
        """
        resolved_path = cls.resolve_config_path(config_path)
        with open(resolved_path, encoding="utf-8") as f:
            config_data = yaml.safe_load(f) or {}

        return cls.model_validate(config_data)

_app_config: AgentConfig | None = None

def get_app_config() -> AgentConfig:
    """Get the Code generate agent config instance."""
    global _app_config

    if _app_config is not None:
        return _app_config


    resolved_path = AgentConfig.resolve_config_path()
    _app_config = AgentConfig.from_file(str(resolved_path))

    return _app_config

if __name__ == "__main__":
    print(get_app_config())